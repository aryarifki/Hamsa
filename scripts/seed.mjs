#!/usr/bin/env node
/**
 * Seeds a demo workspace so a fresh clone has something to look at.
 *
 *   npm run seed
 *
 * Creates (idempotently):
 *   analyst@hamsa.local / hamsa-demo-passphrase
 *   two cases, three watchlist entries, and a handful of synthetic lookups.
 *
 * Requires DATABASE_URL. The schema is created/applied first, so this is safe
 * on an empty database.
 */
import { closePool, ensureSchema, newId, now, run } from "../lib/db.ts";
import { hashPassword } from "../lib/crypto.ts";
import { createUser, userByEmail } from "../lib/users.ts";

const EMAIL = "analyst@hamsa.local";
const PASSWORD = "hamsa-demo-passphrase";

if (!process.env.DATABASE_URL) {
  console.error("[seed] DATABASE_URL is not set (postgres://user:pass@host:5432/hamsa)");
  process.exit(1);
}

await ensureSchema();

if (await userByEmail(EMAIL)) {
  console.log(`[seed] ${EMAIL} already exists — nothing to do.`);
  await closePool();
  process.exit(0);
}

const analyst = await createUser({
  email: EMAIL,
  name: "Demo Analyst",
  passwordHash: hashPassword(PASSWORD),
  role: "analyst",
  credits: 0,
});

await run("UPDATE users SET credits = ? WHERE id = ?", 250, analyst.id);
await run(
  `INSERT INTO ledger (id, user_id, delta, balance_after, reason, created_at)
   VALUES (?, ?, ?, ?, 'seed:demo-balance', ?)`,
  newId(),
  analyst.id,
  250,
  250,
  now(),
);

const cases = [
  {
    title: "Operation Brass Lantern",
    subject: "Synthetic fraud ring (demo data)",
    purpose:
      "Demonstration case for the seeded workspace. All entities below are fictional; the purpose field shows how a lawful basis is recorded.",
    authorizationRef: "DEMO-SOW-2026-001",
  },
  {
    title: "Brand impersonation sweep",
    subject: "Typosquat infrastructure (demo data)",
    purpose:
      "Demonstration case showing how brand-protection findings are grouped. No real infrastructure is referenced.",
    authorizationRef: "DEMO-TICKET-4412",
  },
];

const caseIds = [];
for (const c of cases) {
  const id = newId();
  caseIds.push(id);
  await run(
    `INSERT INTO cases (id, user_id, code, title, subject, purpose, authorization_ref, created_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
    id,
    analyst.id,
    `CASE-${new Date().getFullYear()}-${id.slice(0, 6).toUpperCase()}`,
    c.title,
    c.subject,
    c.purpose,
    c.authorizationRef,
    now(),
  );
}

const demoLookups = [
  { module: "phone", target: "+6281234567890" },
  { module: "ip", target: "203.0.113.42" },
  { module: "email", target: "demo@example.com" },
];

for (const item of demoLookups) {
  const id = newId();
  await run(
    `INSERT INTO lookups (id, user_id, module, target, status, cost, provider, result, created_at, duration_ms)
     VALUES (?, ?, ?, ?, 'ok', 2, 'seed', ?, ?, 42)`,
    id,
    analyst.id,
    item.module,
    item.target,
    JSON.stringify({
      module: item.module,
      target: item.target,
      durationMs: 42,
      sources: [{ name: "Seed data", kind: "offline" }],
      signals: [{ label: "Synthetic seed record — not a live lookup", level: "info" }],
      data: { note: "This record was generated by scripts/seed.mjs for demonstration." },
    }),
    now(),
  );
  await run("INSERT INTO case_items (case_id, lookup_id, added_at) VALUES (?, ?, ?)", caseIds[0], id, now());
}

for (const [module, target, hours] of [
  ["phone", "+628111112222", 24],
  ["ip", "198.51.100.7", 12],
  ["email", "watch@example.com", 72],
]) {
  await run(
    `INSERT INTO watchlist (id, user_id, module, target, interval_hours, created_at)
     VALUES (?, ?, ?, ?, ?, ?)`,
    newId(),
    analyst.id,
    module,
    target,
    hours,
    now(),
  );
}

console.log(`[seed] ready

  email:    ${EMAIL}
  password: ${PASSWORD}
  credits:  250

Change or delete this account before exposing the deployment.`);

await closePool();
