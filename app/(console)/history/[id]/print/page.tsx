import Link from "next/link";
import { notFound } from "next/navigation";
import { requireUser } from "@/lib/auth";
import { lookupById, parsedResult } from "@/lib/lookup";
import { DataView, Signals } from "@/components/DataView";
import { PrintButton } from "@/components/PrintButton";

export const dynamic = "force-dynamic";
export const metadata = { title: "Printable dossier" };

export default async function PrintLookupPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const user = await requireUser();
  const record = lookupById(id, user.id);
  if (!record) notFound();
  const result = parsedResult(record);

  return (
    <div className="mx-auto max-w-[820px] space-y-6">
      <div className="no-print flex items-center justify-between gap-3">
        <Link href={`/history/${record.id}`} className="btn btn-ghost px-2 py-1 text-[12px]">
          ← Back
        </Link>
        <PrintButton />
      </div>

      <header className="border-b border-line pb-5">
        <div className="flex items-center justify-between">
          <div>
            <p className="text-[10px] uppercase tracking-[0.24em] text-faint">Hamsa · OSINT Intelligence Console</p>
            <h1 className="mt-1 text-[22px] font-semibold">Investigation record</h1>
          </div>
          <div className="text-right text-[11px] text-faint">
            <p className="mono">{record.id}</p>
            <p>{new Date(record.created_at).toLocaleString()}</p>
          </div>
        </div>
        <dl className="mt-4 grid grid-cols-2 gap-3 text-[12px] sm:grid-cols-4">
          <div>
            <dt className="text-[10px] uppercase tracking-wider text-faint">Module</dt>
            <dd className="mt-0.5">{record.module}</dd>
          </div>
          <div>
            <dt className="text-[10px] uppercase tracking-wider text-faint">Operator</dt>
            <dd className="mt-0.5">{user.name}</dd>
          </div>
          <div>
            <dt className="text-[10px] uppercase tracking-wider text-faint">Status</dt>
            <dd className="mt-0.5">{record.status}</dd>
          </div>
          <div>
            <dt className="text-[10px] uppercase tracking-wider text-faint">Credits</dt>
            <dd className="mt-0.5">{record.cost}</dd>
          </div>
        </dl>
        <p className="mono mt-4 rounded border border-line bg-surface-2 px-3 py-2 text-[13px]">
          {record.target}
        </p>
      </header>

      {result ? (
        <div className="space-y-5">
          <Signals signals={result.signals} />
          <DataView data={result.data} />
          {result.warnings?.length ? (
            <div className="rounded-lg border border-warn/30 p-3.5 text-[12px]">
              <p className="mb-1 font-semibold uppercase tracking-wider text-warn">Caveats</p>
              <ul className="space-y-1">
                {result.warnings.map((w, i) => (
                  <li key={i}>· {w}</li>
                ))}
              </ul>
            </div>
          ) : null}
          <div className="border-t border-line pt-3 text-[11px] text-faint">
            Sources: {result.sources.map((s) => `${s.name} (${s.kind})`).join(", ")}
          </div>
        </div>
      ) : (
        <p className="text-[13px] text-faint">{record.error ?? "No payload stored."}</p>
      )}

      <footer className="border-t border-line pt-3 text-[10px] leading-relaxed text-faint">
        Generated by Hamsa. Results are derived from public and licensed sources and may be
        incomplete or stale. This record must be handled according to the legal basis recorded in
        the associated case file.
      </footer>
    </div>
  );
}
