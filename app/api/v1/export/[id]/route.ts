function heading(key: string): string {
  return key
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[_-]+/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

function toMarkdown(value: unknown, depth = 3): string {
  const pad = "#".repeat(Math.min(depth, 6));

  if (value === null || value === undefined) return "—\n";
  if (typeof value !== "object") return `${String(value)}\n`;

  if (Array.isArray(value)) {
    if (value.length === 0) return "None.\n";
    if (value.every((v) => typeof v !== "object" || v === null)) {
      return value.map((v) => `- ${String(v)}`).join("\n") + "\n";
    }
    const objects = value as Array<Record<string, unknown>>;
    if (objects.every((o) => typeof o.text === "string")) {
      return (
        objects
          .map(
            (o) =>
              `**${String(o.channel ?? "")}**${o.datetime ? ` · ${String(o.datetime)}` : ""}\n\n${String(
                o.text,
              )}\n\n${o.url ? `[Open](${String(o.url)})` : ""}\n`,
          )
          .join("\n---\n\n") + "\n"
      );
    }
    const cols = Array.from(new Set(objects.flatMap((o) => Object.keys(o)))).slice(0, 6);
    const header = `| ${cols.map(heading).join(" | ")} |`;
    const sep = `| ${cols.map(() => "---").join(" | ")} |`;
    const body = objects
      .slice(0, 200)
      .map(
        (o) =>
          `| ${cols
            .map((c) => {
              const v = o[c];
              return typeof v === "object" && v !== null ? "…" : String(v ?? "—").replace(/\|/g, "\\|");
            })
            .join(" | ")} |`,
      )
      .join("\n");
    return `${header}\n${sep}\n${body}\n`;
  }

  const entries = Object.entries(value as Record<string, unknown>).filter(
    ([, v]) => v !== null && v !== undefined && v !== "",
  );
  return (
    entries
      .map(([k, v]) => {
        if (typeof v === "object" && v !== null) return `${pad} ${heading(k)}\n\n${toMarkdown(v, depth + 1)}`;
        return `- **${heading(k)}:** ${String(v)}`;
      })
      .join("\n") + "\n"
  );
}

function renderMarkdown(record: NonNullable<ReturnType<typeof lookupById>>, result: ModuleResult | null): string {
  const lines: string[] = [];
  lines.push(`# Hamsa investigation record`);
  lines.push("");
  lines.push(`- **Record:** \`${record.id}\``);
  lines.push(`- **Module:** ${record.module}`);
  lines.push(`- **Target:** \`${record.target}\``);
  lines.push(`- **Status:** ${record.status}`);
  lines.push(`- **Credits:** ${record.cost}`);
  lines.push(`- **Created:** ${record.created_at}`);
  lines.push(`- **Duration:** ${record.duration_ms ?? 0} ms`);
  if (record.provider) lines.push(`- **Providers:** ${record.provider}`);
  lines.push("");

  if (!result) {
    lines.push(`> ${record.error ?? "No payload stored."}`);
    return lines.join("\n");
  }

  lines.push("## Signals");
  if (result.signals.length === 0) lines.push("_None._");
  for (const s of result.signals) lines.push(`- **[${s.level}]** ${s.label}${s.detail ? ` — ${s.detail}` : ""}`);
  lines.push("");

  lines.push("## Findings");
  lines.push(toMarkdown(result.data));

  if (result.warnings?.length) {
    lines.push("## Caveats");
    for (const w of result.warnings) lines.push(`- ${w}`);
    lines.push("");
  }

  lines.push("## Sources");
  for (const s of result.sources) lines.push(`- ${s.name} (${s.kind})${s.url ? ` — ${s.url}` : ""}`);

  lines.push("");
  lines.push("---");
  lines.push(
    "_Generated by Hamsa. Derived from public and licensed sources; may be incomplete or stale. Handle according to the legal basis recorded in the associated case._",
  );
  return lines.join("\n");
}

export async function GET(req: NextRequest, ctx: { params: Promise<{ id: string }> }) {
  const auth = await authenticate(req);
  if (!auth) return new Response("Unauthorized", { status: 401 });

  const { id } = await ctx.params;
  const record = lookupById(id, auth.user.id);
  if (!record) return new Response("Not found", { status: 404 });

  const format = new URL(req.url).searchParams.get("format") ?? "json";
  const result = parsedResult(record);

  audit({
    userId: auth.user.id,
    actor: auth.user.email,
    action: "export.generate",
    entity: "lookup",
    entityId: id,
    meta: { format },
  });

  const base = `hamsa-${record.module}-${record.id.slice(0, 8)}`;

  if (format === "md") {
    return new Response(renderMarkdown(record, result), {
      headers: {
        "Content-Type": "text/markdown; charset=utf-8",
        "Content-Disposition": `attachment; filename="${base}.md"`,
        "Cache-Control": "no-store",
      },
    });
  }

  return new Response(
    JSON.stringify({ record: { ...record, result: result ?? undefined }, exportedAt: new Date().toISOString() }, null, 2),
    {
      headers: {
        "Content-Type": "application/json; charset=utf-8",
        "Content-Disposition": `attachment; filename="${base}.json"`,
        "Cache-Control": "no-store",
      },
    },
  );
}
